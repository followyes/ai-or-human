import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resultFiltersUrl, dateInputRange, listAdminResults, deleteAdminResult, clearAdminResults, AdminResultsError, RESULTS_PAGE_SIZE } from "../js/admin-results.js";

const cfg = { projectUrl: "https://fake.supabase.co", publishableKey: "sb_publishable_testing" };
const uuid = "12345678-1234-4123-8123-123456789abc";
const session = { access_token: "admin.jwt" };
const url = (filters) => resultFiltersUrl(filters, { projectUrl: cfg.projectUrl });
let u = url({search:"Marek", mode:"speed-run", difficulty:"hard",sort:"best",fromInstant:"2026-10-23T00:00:00.000Z",untilInstant:"2026-10-24T00:00:00.000Z"});
assert.equal(u.searchParams.get("player_name"), "ilike.*Marek*");
assert.equal(u.searchParams.get("game_mode"), "eq.speed-run");
assert.equal(u.searchParams.get("difficulty"), "eq.hard");
assert.equal(u.searchParams.get("order"), "accuracy_percent.desc,received_at.desc,id.desc");
assert.equal(u.searchParams.get("and"), "(finished_at_client.gte.2026-10-23T00:00:00.000Z,finished_at_client.lt.2026-10-24T00:00:00.000Z)");
u = url({search:uuid});
assert.equal(u.searchParams.get("or"), `(player_id.eq.${uuid},browser_id.eq.${uuid},client_session_id.eq.${uuid},id.eq.${uuid})`);
assert.ok(!u.searchParams.has("player_name"));
u = url({search:"Marek),browser_id.eq.bad",sort:"HACK",mode:"nope"});
assert.ok(!u.toString().includes("browser_id.eq.bad"));
assert.equal(u.searchParams.get("order"), "received_at.desc,id.desc");
assert.ok(!u.searchParams.has("game_mode"));
assert.ok(dateInputRange("2026-10-23", "2026-10-23").untilInstant > dateInputRange("2026-10-23", "2026-10-23").fromInstant);
assert.equal(dateInputRange("2026-02-31", "").fromInstant, null);
assert.equal(dateInputRange("", "").untilInstant, null);
let calls = [];
let returnedRows = [{id:uuid,player_name:"Marek", accuracy_percent:90}];
const fetchImpl = async (target, opts) => {
  calls.push({ target: String(target), opts });
  if (String(target).includes("/rpc/")) return { ok: true, status:200, json: async () => 1 };
  return { ok: true, status:206, headers:{get:(key) => key === "content-range" ? "0-0/55" : null}, json: async()=>returnedRows };
};
const options = {session, config:cfg, fetchImpl};
const result = await listAdminResults({...options, page:1, filters:{search:"Marek"}});
assert.equal(result.total, 55);
assert.equal(result.hasNext, true);
assert.equal(calls[0].opts.headers.Range, `${RESULTS_PAGE_SIZE}-${RESULTS_PAGE_SIZE*2-1}`);
assert.equal(calls[0].opts.headers.Authorization, "Bearer admin.jwt");
assert.equal(calls[0].opts.headers.Prefer, "count=exact");
assert.equal(result.rows[0].player_name, "Marek");
assert.equal(await deleteAdminResult(uuid, options), 1);
assert.equal(calls[1].opts.method, "POST");
assert.deepEqual(JSON.parse(calls[1].opts.body), {p_game_id:uuid});
assert.equal(await clearAdminResults(options), 1);
assert.equal(calls[2].target, "https://fake.supabase.co/rest/v1/rpc/admin_clear_game_results");
assert.deepEqual(JSON.parse(calls[2].opts.body), {});
await assert.rejects(deleteAdminResult("not-uuid", options), {code:"ID"});
await assert.rejects(listAdminResults({...options, session:null}), {code:"SESSION"});
await assert.rejects(listAdminResults({...options, fetchImpl: async() => ({ok:false,status:403})}), {code:"SESSION",status:403});
await assert.rejects(clearAdminResults({...options, fetchImpl: async() => ({ok:true,json: async()=>({not:"count"})})}), {code:"RESPONSE"});
assert.ok(AdminResultsError.prototype instanceof Error);
const html = await readFile(new URL("../admin/index.html", import.meta.url), "utf8");
for (const id of ["results-workspace", "tab-library", "tab-results", "results-clear", "results-search", "results-mode", "results-difficulty", "results-date-from", "results-date-to", "results-sort", "results-status", "results-list", "results-prev", "results-next", "results-page-label"]) {
  assert.ok(html.includes(`id="${id}"`), `Missing Admin UI control ${id}`);
}
const code = await readFile(new URL("../admin/admin.js", import.meta.url), "utf8");
assert.ok(code.includes('resultsPanel.clear()') && code.includes('resultsPanel.setActive(resultsActive)'));
const ui = await readFile(new URL("../js/admin-results-ui.js", import.meta.url), "utf8");
assert.ok(ui.includes("name.textContent = record.player_name"), "public names must use textContent");
assert.ok(!ui.includes("innerHTML"), "no untrusted HTML injection");
assert.ok(html.includes('id="admin-workspace"'));
const game = await readFile(new URL("../index.html", import.meta.url), "utf8");
assert.ok(game.includes('id="player-name"') && !game.includes('profile-dialog__eyebrow'), "profile dialog compact, controls preserved");
console.log("R2 TEST PASS — server query filters & IDs, paging, RPC, access failures, DOM contracts, compact profile");
